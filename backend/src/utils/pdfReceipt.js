const PDFDocument = require('pdfkit');

/**
 * Generate a PDF receipt buffer using PDFKit.
 *
 * @param {Object} paymentData
 * @returns {Promise<Buffer>}
 */
const generatePdfReceiptBuffer = (paymentData) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const buffers = [];

      doc.on('data', buffers.push.bind(buffers));
      doc.on('end', () => {
        const pdfData = Buffer.concat(buffers);
        resolve(pdfData);
      });
      doc.on('error', (err) => reject(err));

      // Header
      doc
        .fillColor('#1E293B')
        .fontSize(22)
        .font('Helvetica-Bold')
        .text('LivingLink Residential Society', { align: 'center' });

      doc
        .fontSize(10)
        .font('Helvetica')
        .fillColor('#64748B')
        .text('Official Payment & Dues Receipt', { align: 'center' })
        .moveDown(1.5);

      // Horizontal separator rule
      doc.strokeColor('#CBD5E1').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke().moveDown(1.5);

      // Receipt Meta Block
      doc.fillColor('#0F172A').fontSize(12).font('Helvetica-Bold');
      doc.text(`Receipt Number: ${paymentData.receiptNumber}`);
      doc.font('Helvetica').fontSize(10).fillColor('#334155');
      doc.text(`Date of Issue: ${new Date(paymentData.transactionDate || Date.now()).toUTCString()}`);
      doc.text(`Transaction Reference: ${paymentData.paymentId}`);
      doc.moveDown(1);

      // Resident Details Table / Box
      doc.rect(50, doc.y, 495, 80).fillAndStroke('#F8FAFC', '#E2E8F0');
      const boxY = doc.y - 75;

      doc.fillColor('#1E293B').font('Helvetica-Bold').fontSize(10);
      doc.text('RESIDENT DETAILS', 65, boxY);
      doc.font('Helvetica').fontSize(9).fillColor('#475569');
      doc.text(`Name: ${paymentData.ownerName}`, 65, boxY + 18);
      doc.text(`Tower: ${paymentData.tower}`, 65, boxY + 34);
      doc.text(`Flat: ${paymentData.flatNumber}`, 65, boxY + 50);

      doc.text(`Contact: ${paymentData.ownerPhone || 'N/A'}`, 300, boxY + 18);
      doc.text(`Email: ${paymentData.ownerEmail || 'N/A'}`, 300, boxY + 34);
      doc.moveDown(4);

      // Payment Details
      doc.fillColor('#0F172A').fontSize(11).font('Helvetica-Bold').text('PAYMENT DETAILS', 50, doc.y);
      doc.moveDown(0.5);

      // Line items table header
      const tableTop = doc.y;
      doc.rect(50, tableTop, 495, 24).fill('#E2E8F0');
      doc.fillColor('#1E293B').fontSize(9).font('Helvetica-Bold');
      doc.text('DESCRIPTION', 60, tableTop + 7);
      doc.text('PAYMENT TYPE', 260, tableTop + 7);
      doc.text('METHOD', 370, tableTop + 7);
      doc.text('AMOUNT (INR)', 450, tableTop + 7, { align: 'right', width: 85 });

      // Line item row
      const rowTop = tableTop + 24;
      doc.rect(50, rowTop, 495, 30).fill('#FFFFFF').stroke('#E2E8F0');
      doc.fillColor('#334155').fontSize(9).font('Helvetica');
      doc.text(paymentData.description || 'Society Maintenance / Amenity Subscription', 60, rowTop + 10);
      doc.text(paymentData.paymentType, 260, rowTop + 10);
      doc.text(paymentData.paymentMethod || 'DEMO', 370, rowTop + 10);
      const amountRupees = (paymentData.amountInPaise / 100).toFixed(2);
      doc.font('Helvetica-Bold').text(`₹ ${amountRupees}`, 450, rowTop + 10, { align: 'right', width: 85 });

      // Total summary box
      const totalTop = rowTop + 40;
      doc.rect(345, totalTop, 200, 32).fill('#F1F5F9').stroke('#CBD5E1');
      doc.fillColor('#0F172A').fontSize(11).font('Helvetica-Bold');
      doc.text('TOTAL PAID:', 355, totalTop + 10);
      doc.fillColor('#059669').text(`₹ ${amountRupees}`, 440, totalTop + 10, { align: 'right', width: 95 });

      // Status Badge
      doc.moveDown(4);
      doc.fillColor('#059669').fontSize(12).font('Helvetica-Bold').text(`STATUS: ${paymentData.status || 'SUCCESS'}`, 50, totalTop + 55);

      // Disclaimer & Footer
      const disclaimerTop = 680;
      doc.rect(50, disclaimerTop, 495, 45).fill('#FEF3C7').stroke('#FDE68A');
      doc.fillColor('#92400E').fontSize(8).font('Helvetica-Bold');
      doc.text('IMPORTANT DISCLAIMER (DEMO PAYMENT SIMULATION):', 60, disclaimerTop + 8);
      doc.font('Helvetica').fillColor('#78350F');
      doc.text(
        'This receipt is generated by the LivingLink Demo Payment Simulation Engine for testing society workflows. No real monetary transactions or banking charges have been processed.',
        60,
        disclaimerTop + 20,
        { width: 475 }
      );

      doc.fillColor('#94A3B8').fontSize(8).text('LivingLink Society Management Platform — Generated Automatically', 50, 750, { align: 'center' });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};

module.exports = {
  generatePdfReceiptBuffer
};
